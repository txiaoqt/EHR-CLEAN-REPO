import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read = path => readFileSync(path, 'utf8');
const app = read('src/App.jsx');
const auth = read('src/AuthContext.jsx');
const login = read('src/pages/Login.jsx');
const admin = read('src/admin/AdminPortal.jsx');
assert.ok(app.includes('IS_ADMIN_SURFACE ? <AdminPortal />'));
assert.ok(app.includes('{IS_STAFF_SURFACE && ('));
assert.ok(app.includes('isRoleCompatibleWithSurface(userRole)'));
assert.ok(login.includes('!isRoleCompatibleWithSurface(userRole)'));
assert.ok(auth.includes("supabase.rpc('get_my_portal_identity')"));
assert.ok(!auth.includes("metaRole === 'admin'"));
assert.ok(auth.includes('data.active === false'));
assert.ok(admin.includes("user?.role !== 'admin'"));
assert.ok(admin.includes("adminAction('login'"));
assert.ok(!admin.includes('EHR_ADMIN_INITIAL_PASSWORD'));
assert.ok(!read('src/admin/adminApi.js').includes('SERVICE_ROLE'));
console.log('PASS: portal routing, live account checks, and browser credential boundaries.');
